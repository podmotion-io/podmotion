// ctr_masked_mount_test.go — live-bug regression for the postgres checkpoint failure (2026-07-10).
//
// Live failure: postgres (TCPPreservationMode=None → tcpEstablished=false) checkpointed via
// `ctr tasks checkpoint`, whose runc-driven CRIU invocation carries NONE of the agent's
// --skip-mnt list. CRIU's mountpoint-dump pass aborted on the masked bind over /proc/interrupts:
//
//	Error (criu/mount.c:753): mnt: 625:./proc/interrupts doesn't have a proper root mount
//	Dumping FAILED.
//
// Because the failure is a MOUNT error, not a TCP one, the old classifier fell through to the
// fatal `return err` branch — it never emitted ErrCtrInFlightTCP, so the Checkpoint RPC hard-failed
// at server.go and never reached the raw go-criu Dump path where the dump-side skipMnts would have
// skipped /proc/interrupts. These tests pin the fix: a masked-mount dump abort classifies as
// ErrCtrMaskedMount (which the Checkpoint RPC now treats as a raw-CRIU fall-through, exactly like
// ErrCtrInFlightTCP), while a genuinely-fatal ctr failure stays fatal.

import (
	"encoding/json"
	"errors"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

func TestClassifyCtrCheckpointFailure_MaskedMount(t *testing.T) {
	rawErr := errors.New("exit status 1")
	// Verbatim CRIU mount-pass diagnostic from the live postgres dump.log (2026-07-10).
	out := "ctr: runc did not terminate successfully: exit status 1\n" +
		"--- criu-dump.log ---\n" +
		"(00.100258) Error (criu/mount.c:753): mnt: 625:./proc/interrupts doesn't have a proper root mount\n" +
		"(00.100300) Dumping FAILED.\n"

	// postgres is None → tcpEstablished=false; dump log WAS readable.
	got := classifyCtrCheckpointFailure(out, rawErr, true, false)
	if !errors.Is(got, ErrCtrMaskedMount) {
		t.Fatalf("masked-mount dump abort must classify as ErrCtrMaskedMount (raw-CRIU fall-through); got %v", got)
	}
	// It must NOT be misclassified as the TCP class.
	if errors.Is(got, ErrCtrInFlightTCP) {
		t.Errorf("masked-mount failure must not be ErrCtrInFlightTCP")
	}
}

func TestClassifyCtrCheckpointFailure_InFlightTCPStillClassified(t *testing.T) {
	rawErr := errors.New("exit status 1")
	out := "criu: inet: Connected TCP socket, consider using --tcp-established option\nsk-inet.c\n"
	got := classifyCtrCheckpointFailure(out, rawErr, true, true)
	if !errors.Is(got, ErrCtrInFlightTCP) {
		t.Fatalf("established-TCP failure must classify as ErrCtrInFlightTCP; got %v", got)
	}
}

func TestClassifyCtrCheckpointFailure_GenuineFatalStaysFatal(t *testing.T) {
	rawErr := errors.New("exit status 137")
	// An OOM/other fatal failure with a readable dump log and no mount/TCP diagnostic must NOT be
	// coerced into a fall-through sentinel — that would loop the raw-CRIU path onto the same wall.
	out := "ctr: task killed (OOM)\n--- criu-dump.log ---\n(00.5) Error (criu/cr-dump.c): killed\n"
	got := classifyCtrCheckpointFailure(out, rawErr, true, false)
	if errors.Is(got, ErrCtrMaskedMount) || errors.Is(got, ErrCtrInFlightTCP) {
		t.Fatalf("genuine fatal ctr failure must not classify as a raw-CRIU fall-through sentinel; got %v", got)
	}
	if !errors.Is(got, rawErr) {
		t.Errorf("fatal classification must wrap the raw exec error; got %v", got)
	}
}

func TestClassifyCtrCheckpointFailure_UnreadableLogFailSafeTCP(t *testing.T) {
	rawErr := errors.New("exit status 1")
	// Dump log unreadable + TCP preservation requested → ADR-0213 D2 fail-safe to TCP class so the
	// migration falls back to raw CRIU with --tcp-established rather than aborting.
	out := "ctr: runc did not terminate successfully: exit status 1\n"
	got := classifyCtrCheckpointFailure(out, rawErr, false, true)
	if !errors.Is(got, ErrCtrInFlightTCP) {
		t.Fatalf("unreadable log + tcpEstablished must fail-safe to ErrCtrInFlightTCP; got %v", got)
	}
}

// ---- ADR-0417: mount-recreatability classification / destination-rebind coverage ----
//
// The tests below exercise the ACTUAL production function (patchCheckpointImages), not a
// hand-copied re-implementation, against synthetic pycriu mountpoints-*.img fixtures built the
// same way adr0389_dev_ext_mount_scan_test.go / adr0415_capture_gate_test.go already do in this
// package. Three cases, matching ADR-0417 §P-VERIFY assertion 7 exactly:
//
//	(a) a TMPFS-fstype mount -> Class RECREATABLE / internalize branch
//	(b) an fstype-0 (block-fs) regular-file bind, carrying a LITERAL ext_key (the shape that also
//	    exercises CRIU_REATTACH_EXT_MOUNT_MAP emission) -> Class DESTINATION-REBIND branch with
//	    root/source rewrite
//	(c) the same DESTINATION-REBIND-eligible mount with NO resolvable destination target -> the
//	    ADR-0417 fail-closed hard-stop (EXTERNAL_MOUNT_UNRESOLVED)

// adr0417CorpusGenPy writes a mountpoints-10.img with three entries: an overlay root, a TMPFS
// /dev/shm (ext_key="CRIU:AUTOGENERATED", the RECREATABLE case), and a fstype=0 (FSTYPE_UNSUPPORTED
// — real block filesystem, e.g. a kubelet regular-file bind) /etc/hosts entry carrying a LITERAL
// (non-"CRIU:AUTOGENERATED") ext_key so the DESTINATION-REBIND branch's CRIU_REATTACH_EXT_MOUNT_MAP
// token emission is exercised too (mirrors the Longhorn/literal-ext_key shape carve-out (a) already
// proves — ADR-0417 reuses that same mechanism unmodified). fstype values match the real CRIU
// mnt.proto enum this package's other corpus tests already use (TMPFS=5; see adr0389/adr0415
// fixtures for the same numbering) — fstype is a raw protobuf uint32 in pycriu, never a decoded
// string (verified empirically against the installed pycriu in ADR-0417's implementation).
const adr0417CorpusGenPy = `
import sys, os
import pycriu

d = sys.argv[1]
mnts = [
    {'fstype': 0, 'mnt_id': 1, 'root_dev': 0, 'parent_mnt_id': 0, 'flags': 0,
     'root': '/', 'mountpoint': '/', 'source': 'overlay', 'options': '', 'sb_flags': 0},
    {'fstype': 5, 'mnt_id': 2, 'root_dev': 0, 'parent_mnt_id': 1, 'flags': 0,
     'root': '/', 'mountpoint': '/dev/shm', 'source': 'shm', 'options': '', 'sb_flags': 0,
     'ext_key': 'CRIU:AUTOGENERATED'},
    {'fstype': 0, 'mnt_id': 3, 'root_dev': 0, 'parent_mnt_id': 1, 'flags': 0,
     'root': '/var/lib/kubelet/pods/SRCUID/etc-hosts', 'mountpoint': '/etc/hosts',
     'source': '/var/lib/kubelet/pods/SRCUID/etc-hosts', 'options': '', 'sb_flags': 0,
     'ext_key': '/etc/hosts'},
]
with open(os.path.join(d, 'mountpoints-10.img'), 'wb') as f:
    pycriu.images.dump({'magic': 'MNTS', 'entries': mnts}, f)
print('CORPUS_OK')
`

// writeADR0417Corpus generates the fixture above into ckptDir.
func writeADR0417Corpus(t *testing.T, pypath string, extraEnv []string, ckptDir string) {
	t.Helper()
	genPath := filepath.Join(t.TempDir(), "adr0417-corpus-gen.py")
	if err := os.WriteFile(genPath, []byte(adr0417CorpusGenPy), 0o600); err != nil {
		t.Fatalf("write corpus generator: %v", err)
	}
	cmd := exec.Command("python3", genPath, ckptDir)
	cmd.Env = append(extraEnv, "PYTHONPATH="+pypath)
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("generate ADR-0417 corpus: %v\noutput: %s", err, out)
	}
	if !strings.Contains(string(out), "CORPUS_OK") {
		t.Fatalf("corpus generator did not report CORPUS_OK; output: %s", out)
	}
}

// readMountpointsEntries reads back every entry across all mountpoints-*.img files in ckptDir
// (post-patch state) via a small pycriu read-back subprocess, so the test verifies what actually
// landed on disk rather than trusting patchCheckpointImages' own bookkeeping.
func readMountpointsEntries(t *testing.T, pypath string, extraEnv []string, ckptDir string) []map[string]interface{} {
	t.Helper()
	const readBackPy = `
import sys, os, glob, json
import pycriu
d = sys.argv[1]
result = []
for p in glob.glob(os.path.join(d, 'mountpoints-*.img')):
    with open(p, 'rb') as f:
        img = pycriu.images.load(f)
    result.extend(img.get('entries', []))
print(json.dumps(result))
`
	scriptPath := filepath.Join(t.TempDir(), "adr0417-readback.py")
	if err := os.WriteFile(scriptPath, []byte(readBackPy), 0o600); err != nil {
		t.Fatalf("write readback script: %v", err)
	}
	cmd := exec.Command("python3", scriptPath, ckptDir)
	cmd.Env = append(extraEnv, "PYTHONPATH="+pypath)
	out, err := cmd.Output()
	if err != nil {
		t.Fatalf("readback script failed: %v", err)
	}
	var entries []map[string]interface{}
	if err := json.Unmarshal(out, &entries); err != nil {
		t.Fatalf("parse readback json: %v\noutput: %s", err, out)
	}
	return entries
}

func findMountEntry(entries []map[string]interface{}, mountpoint string) map[string]interface{} {
	for _, e := range entries {
		if mp, _ := e["mountpoint"].(string); mp == mountpoint {
			return e
		}
	}
	return nil
}

// TestPatchCheckpointImages_ADR0417_RecreatableInternalized covers §P-VERIFY 7(a): a TMPFS-fstype
// mount (/dev/shm) must still take the Class RECREATABLE / internalize branch — ext_key cleared,
// root rewritten to "/" — exactly as ADR-0415 already proved (regression guard: ADR-0417 must not
// have narrowed or altered this branch).
func TestPatchCheckpointImages_ADR0417_RecreatableInternalized(t *testing.T) {
	pypath, extraEnv := pycriuEnv(t)
	ckptDir := t.TempDir()
	writeADR0417Corpus(t, pypath, extraEnv, ckptDir)

	// Resolve a destination target for /etc/hosts too, so this run does not fail closed on the
	// unrelated DESTINATION-REBIND entry in the same fixture — this test is scoped to the
	// RECREATABLE branch only.
	hostTargets := map[string]string{"/etc/hosts": "/var/lib/kubelet/pods/DESTUID/etc-hosts"}
	if _, _, err := patchCheckpointImages(ckptDir, nil, nil, hostTargets, nil); err != nil {
		t.Fatalf("patchCheckpointImages returned error: %v", err)
	}

	entries := readMountpointsEntries(t, pypath, extraEnv, ckptDir)
	shm := findMountEntry(entries, "/dev/shm")
	if shm == nil {
		t.Fatal("/dev/shm entry missing from patched mountpoints image")
	}
	if extKey, ok := shm["ext_key"]; ok && extKey != "" && extKey != nil {
		t.Errorf("Class RECREATABLE /dev/shm must have ext_key cleared (internalized); got %v", extKey)
	}
	if root, _ := shm["root"].(string); root != "/" {
		t.Errorf("Class RECREATABLE /dev/shm must have root rewritten to \"/\"; got %q", root)
	}
}

// TestPatchCheckpointImages_ADR0417_DestinationRebindRewritesAndEmitsExtMountMap covers
// §P-VERIFY 7(b): an fstype=0 (FSTYPE_UNSUPPORTED — real block filesystem) regular-file bind must
// take the NEW Class DESTINATION-REBIND branch: ext_key PRESERVED (not popped), root/source
// rewritten to the resolved destination path, and — because this fixture's ext_key is a LITERAL
// value (not CRIU's "CRIU:AUTOGENERATED" autodetect constant) — a CRIU_REATTACH_EXT_MOUNT_MAP token
// emitted so buildCRIURestoreArgs can supply the corresponding --ext-mount-map entry.
func TestPatchCheckpointImages_ADR0417_DestinationRebindRewritesAndEmitsExtMountMap(t *testing.T) {
	pypath, extraEnv := pycriuEnv(t)
	ckptDir := t.TempDir()
	writeADR0417Corpus(t, pypath, extraEnv, ckptDir)

	const wantHostTarget = "/var/lib/kubelet/pods/DESTUID/etc-hosts"
	hostTargets := map[string]string{"/etc/hosts": wantHostTarget}
	_, reattachExtMountMap, err := patchCheckpointImages(ckptDir, nil, nil, hostTargets, nil)
	if err != nil {
		t.Fatalf("patchCheckpointImages returned error: %v", err)
	}

	// CRIU_REATTACH_EXT_MOUNT_MAP token: emitted because this fixture's /etc/hosts ext_key is the
	// literal "/etc/hosts", not "CRIU:AUTOGENERATED" — same literal-ext_key shape carve-out (a)
	// already proves for Tier1-Longhorn (ReattachExtMountMapEntry doc, server.go).
	found := false
	for _, m := range reattachExtMountMap {
		if m.Mountpoint == "/etc/hosts" {
			found = true
			if m.HostTarget != wantHostTarget {
				t.Errorf("CRIU_REATTACH_EXT_MOUNT_MAP host_target: got %q, want %q", m.HostTarget, wantHostTarget)
			}
			if m.ExtKey != "/etc/hosts" {
				t.Errorf("CRIU_REATTACH_EXT_MOUNT_MAP ext_key: got %q, want %q", m.ExtKey, "/etc/hosts")
			}
		}
	}
	if !found {
		t.Errorf("expected a CRIU_REATTACH_EXT_MOUNT_MAP entry for /etc/hosts (literal ext_key, DESTINATION-REBIND class); got %+v", reattachExtMountMap)
	}

	entries := readMountpointsEntries(t, pypath, extraEnv, ckptDir)
	hosts := findMountEntry(entries, "/etc/hosts")
	if hosts == nil {
		t.Fatal("/etc/hosts entry missing from patched mountpoints image")
	}
	if extKey, _ := hosts["ext_key"].(string); extKey != "/etc/hosts" {
		t.Errorf("Class DESTINATION-REBIND /etc/hosts must PRESERVE its ext_key (not internalize); got %q", extKey)
	}
	if root, _ := hosts["root"].(string); root != wantHostTarget {
		t.Errorf("Class DESTINATION-REBIND /etc/hosts root must be rewritten to the destination target; got %q, want %q", root, wantHostTarget)
	}
	if source, _ := hosts["source"].(string); source != wantHostTarget {
		t.Errorf("Class DESTINATION-REBIND /etc/hosts source must be rewritten to the destination target; got %q, want %q", source, wantHostTarget)
	}
}

// TestPatchCheckpointImages_ADR0417_UnresolvedDestinationRebindHardStops covers §P-VERIFY 7(c) and
// the ADR-0417 Decision's explicit fail-closed requirement: "Fail-closed if the destination target
// cannot be resolved (never restore a mount whose recorded source exists only on the source node)."
// With NO entry for /etc/hosts in reattachHostTargets, patchCheckpointImages must hard-stop with
// ExternalMountUnresolvedError rather than silently falling back to internalizing the mount (which
// would reintroduce the exact ADR-0415 defect this ADR fixes).
func TestPatchCheckpointImages_ADR0417_UnresolvedDestinationRebindHardStops(t *testing.T) {
	pypath, extraEnv := pycriuEnv(t)
	ckptDir := t.TempDir()
	writeADR0417Corpus(t, pypath, extraEnv, ckptDir)

	// No host target supplied for /etc/hosts (or /dev/shm, which does not need one — RECREATABLE).
	_, _, err := patchCheckpointImages(ckptDir, nil, nil, nil, nil)
	if err == nil {
		t.Fatal("expected patchCheckpointImages to hard-stop when a DESTINATION-REBIND target cannot be resolved, got nil error")
	}
	var unresolved *ExternalMountUnresolvedError
	if !errors.As(err, &unresolved) {
		t.Fatalf("expected *ExternalMountUnresolvedError; got %v (%T)", err, err)
	}
	if unresolved.Reason != "destination_rebind_target_unresolved" {
		t.Errorf("expected reason %q; got %q", "destination_rebind_target_unresolved", unresolved.Reason)
	}
}
